export const GLYPH_W = 3;
export const GLYPH_H = 5;

// Pre-parse into arrays of [dx, dy] lit pixels.
export const GLYPHS = Object.fromEntries(
  Object.entries(RAW).map(([ch, rows]) => {
    const pts = [];
    rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && pts.push([x, y])));
    return [ch, pts];
  }),
);

export function textWidth(str, scale = 1) {
  return str.length ? (str.length * 4 - 1) * scale : 0;
}
