// Pre-parse into arrays of [dx, dy] lit pixels.
const parse = (raw) =>
  Object.fromEntries(
    Object.entries(raw).map(([ch, rows]) => {
      const pts = [];
      rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && pts.push([x, y])));
      return [ch, pts];
    }),
  );

export const FONTS = {
  big: { w: 5, h: 7, glyphs: parse(BIG) },
  small: { w: 3, h: 5, glyphs: parse(SMALL) },
};

export function textWidth(str, scale = 1, font = 'big') {
  const f = FONTS[font];
  return str.length ? (str.length * (f.w + 1) - 1) * scale : 0;
}
