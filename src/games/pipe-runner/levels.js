// Levels are 8 tiles tall. Legend:
//   #  ground      B  brick       ?  coin block   M  mushroom block   X  hard block
//   [] pipe top    {} pipe body   o  coin         G  walker enemy     S  spiky enemy
//   P  player start               F  flagpole base                   c  castle (bottom-left)
//   =  background brick (decorative ceiling, not solid)
// Each level is a list of segments; rows inside a segment must be equal length.

function join(segments) {
  const rows = Array.from({ length: 8 }, () => '');
  for (const seg of segments) {
    if (seg.length !== 8) throw new Error('segment must have 8 rows');
    const w = Math.max(...seg.map((r) => r.length));
    seg.forEach((r, i) => (rows[i] += r.padEnd(w, '.')));
  }
  return rows;
}

